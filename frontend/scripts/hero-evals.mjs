// Pre-computes Stockfish evaluations for the home-page hero game so the home page
// never has to download the engine. Run: node frontend/scripts/hero-evals.mjs
// Output: frontend/features/home/hero-game-data.ts

import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Chess } from "chessops/chess";
import { makeFen } from "chessops/fen";
import { parsePgn, startingPosition } from "chessops/pgn";
import { makeSanAndPlay, parseSan } from "chessops/san";
import { makeUci } from "chessops/util";

const require = createRequire(import.meta.url);
const DEPTH = 18;

// Anderssen vs Kieseritzky, London 1851 ("The Immortal Game") — public domain.
const PGN = `[Event "London casual game"]
[Site "London"]
[Date "1851.06.21"]
[White "Adolf Anderssen"]
[Black "Lionel Kieseritzky"]
[Result "1-0"]

1. e4 e5 2. f4 exf4 3. Bc4 Qh4+ 4. Kf1 b5 5. Bxb5 Nf6 6. Nf3 Qh6 7. d3 Nh5 8. Nh4 Qg5
9. Nf5 c6 10. g4 Nf6 11. Rg1 cxb5 12. h4 Qg6 13. h5 Qg5 14. Qf3 Ng8 15. Bxf4 Qf6
16. Nc3 Bc5 17. Nd5 Qxb2 18. Bd6 Bxg1 19. e5 Qxa1+ 20. Ke2 Na6 21. Nxg7+ Kd8
22. Qf6+ Nxf6 23. Be7# 1-0`;

const game = parsePgn(PGN)[0];
const pos = startingPosition(game.headers).unwrap();
const plies = [{ fen: makeFen(pos.toSetup()) }];
for (const node of game.moves.mainlineNodes()) {
  const move = parseSan(pos, node.data.san);
  if (!move) throw new Error(`Illegal move ${node.data.san}`);
  const uci = makeUci(move);
  const san = makeSanAndPlay(pos, move);
  plies.push({ fen: makeFen(pos.toSetup()), san, uci });
}

const engine = require("stockfish")("single", onLine);
let resolveSearch = () => {};
let last = null;
function onLine(line) {
  const m = line.match(/^info .*\bdepth (\d+)\b.*\bscore (cp|mate) (-?\d+)/);
  if (m) last = { kind: m[2], value: Number(m[3]) };
  if (line.startsWith("bestmove")) resolveSearch();
}
const search = (fen) =>
  new Promise((resolve) => {
    last = null;
    resolveSearch = () => resolve(last);
    engine.processCommand(`position fen ${fen}`);
    engine.processCommand(`go depth ${DEPTH}`);
  });

engine.processCommand("uci");
engine.processCommand("setoption name Hash value 64");
engine.processCommand("ucinewgame");

const out = [];
for (const [i, ply] of plies.entries()) {
  const p = Chess.fromSetup((await import("chessops/fen")).parseFen(ply.fen).unwrap()).unwrap();
  let score;
  if (p.isCheckmate()) score = { mate: 0 };
  else {
    const r = await search(ply.fen);
    const sign = p.turn === "white" ? 1 : -1; // UCI scores are side-to-move relative
    score = r.kind === "mate" ? { mate: r.value * sign } : { cp: r.value * sign };
  }
  out.push({ ...ply, score });
  process.stdout.write(`\r${i + 1}/${plies.length}`);
}
engine.terminate();

const file = join(dirname(fileURLToPath(import.meta.url)), "..", "features", "home", "hero-game-data.ts");
const body = `// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by frontend/scripts/hero-evals.mjs (Stockfish 19, depth ${DEPTH}). Do not edit by hand.
// Game: Anderssen vs Kieseritzky, London 1851 ("The Immortal Game"), public domain.

import type { Score } from "@kingside/chess-core";

export interface HeroPly {
  fen: string;
  san?: string;
  uci?: string;
  /** White-POV score after this ply; mate 0 = checkmate on the board. */
  score: Score;
}

/** A famous game shown on the home page (hero board + legendary games section). */
export interface LegendaryGame {
  id: string;
  white: string;
  black: string;
  event: string;
  result: string;
  pgn: string;
  plies: HeroPly[];
}

export const HERO_GAME = {
  white: "Adolf Anderssen",
  black: "Lionel Kieseritzky",
  event: "London, 1851",
  title: "The Immortal Game",
} as const;

export const HERO_PLIES: HeroPly[] = ${JSON.stringify(out, null, 2)};

export const IMMORTAL: LegendaryGame = {
  id: "immortal",
  white: HERO_GAME.white,
  black: HERO_GAME.black,
  event: HERO_GAME.event,
  result: "1-0",
  pgn: \`[White "Adolf Anderssen"]
[Black "Lionel Kieseritzky"]
[Event "London, 1851"]
[Result "1-0"]

\${HERO_PLIES.slice(1)
  .map((p, i) => \`\${i % 2 === 0 ? \`\${i / 2 + 1}.\` : ""}\${p.san}\`)
  .join(" ")} 1-0\`,
  plies: HERO_PLIES,
};
`;
await writeFile(file, body);
console.log(`\nwrote ${file}`);
